export function withProgressiveReadings(levels: ExamLevel[], chapters: ReadingChapter[]): ExamLevel[] {
  if (levels.length !== chapters.length) {
    throw new Error(`Reading series has ${chapters.length} chapters for ${levels.length} levels.`);
  }
  return levels.map((level, index) => ({
    ...level,
    article: {
      ...level.article,
      traditional: chapters.slice(0, index + 1).map((chapter) => chapter.traditional).join('\n\n'),
      simplified: chapters.slice(0, index + 1).map((chapter) => chapter.simplified).join('\n\n'),
    },
  }));
}
